"""Complete D's frozen B/C analysis against the existing, immutable D reference.

python -m Part_D_Drift.joint --data PATH --reference-output outputs/part_d_complete
"""

import argparse
import json
from pathlib import Path
import shutil

import pandas as pd
from threadpoolctl import threadpool_limits

from Part_A.features import get_data, get_features
from .analysis import prepare_predictions
from .drift import monitor_config
from .evaluation import evaluate_joint
from .handover import export_demand_and_baselines, file_sha256
from .run import environment_info


EXPECTED_GROUPS = {(task, model, "frozen") for task, names in
                   (("demand", ("ridge_regression", "random_forest")),
                    ("price", ("logistic_regression", "random_forest"))) for model in names}
EXPECTED_GROUPS |= {(task, model, "baseline") for task in ("demand", "price")
                    for model in ("yesterday_baseline", "last_week_baseline")}


def verify_coverage(predictions):
    groups = predictions.groupby(["task", "model", "strategy"], observed=True, sort=True)
    if set(groups.groups) != EXPECTED_GROUPS:
        raise ValueError("Need four frozen B/C models and both baselines for each task")
    expected_days = pd.date_range("2015-01-01", "2026-10-31")
    rows = []
    for keys, group in groups:
        days = pd.DatetimeIndex(group.market_day.unique()).sort_values()
        if len(group) != len(expected_days) * 48 or len(days) != len(expected_days) or len(days.difference(expected_days)):
            raise ValueError(f"Incomplete or out-of-period prediction coverage: {keys}")
        rows.append({"task": keys[0], "model": keys[1], "strategy": keys[2], "n_days": len(days),
                     "n_half_hours": len(group), "start": str(days.min().date()), "end": str(days.max().date())})
    return pd.DataFrame(rows)


def _records(frame):
    return frame.astype(object).where(pd.notna(frame), None).to_dict(orient="records")


def run(args):
    reference = Path(args.reference_output).resolve()
    output = Path(args.output).resolve() if args.output else reference / "joint"
    if output.exists() and any(output.iterdir()):
        raise ValueError("Joint output already contains results; use a new or empty directory")
    env = environment_info()
    if args.strict_versions and not env["matches_official_core"]:
        raise ValueError("Use Python 3.11 and the official core dependency versions")
    core = json.loads((reference / "run_summary.json").read_text())
    data_hash = file_sha256(args.data)
    if core["data_sha256"] != data_hash:
        raise ValueError("B/C evaluation and the existing D reference must use the same released CSV")
    reference_paths = ["tables/day_assignments.csv", "tables/input_drift_daily.csv",
                       "artifacts/day_types.joblib", "artifacts/input_detector.joblib", "market_sources.json"]
    hashes = {name: file_sha256(reference / name) for name in reference_paths}
    assignments = pd.read_csv(reference / "tables/day_assignments.csv", index_col=0, parse_dates=True)
    signals = pd.read_csv(reference / "tables/input_drift_daily.csv", index_col=0, parse_dates=True)
    sources = json.loads((reference / "market_sources.json").read_text())
    print("Loading official truth; preserving D's fitted reference and alarm dates...", flush=True)
    observed = get_data(path=args.data)
    output.mkdir(parents=True, exist_ok=True)
    if args.demand_handover:
        cache = Path(args.demand_handover)
        handover = json.loads((cache / "demand_handover.json").read_text())
        if handover["data_sha256"] != data_hash or handover["random_forest"]["sha256"] != file_sha256(args.demand_rf):
            raise ValueError("Cached demand handover has different source data/model")
        for name, digest in handover["generated_files_sha256"].items():
            if file_sha256(cache / name) != digest:
                raise ValueError(f"Cached handover changed: {name}")
        if handover["source_sha256"] != file_sha256(Path(__file__).with_name("handover.py")):
            raise ValueError("Cached handover was generated by a different exporter source")
        shutil.copytree(cache, output, dirs_exist_ok=True)
        demand = pd.read_csv(output / "predictions/demand_predictions_for_part_d.csv.gz")
        baselines = pd.read_csv(output / "predictions/baseline_predictions.csv.gz")
        _, truth, _ = get_features(config=monitor_config(), data=observed)
    else:
        demand, baselines, truth, handover = export_demand_and_baselines(observed, args.demand_rf, output)
        handover["data_sha256"] = data_hash
        handover["source_sha256"] = file_sha256(Path(__file__).with_name("handover.py"))
        handover["generated_files_sha256"] = {str(p.relative_to(output)): file_sha256(p)
                                              for p in sorted(output.rglob("*")) if p.is_file()}
        (output / "demand_handover.json").write_text(json.dumps(handover, indent=2))
    price = pd.read_csv(args.price_predictions)
    print("Validating all interval predictions against official targets and full-day coverage...", flush=True)
    predictions = prepare_predictions(pd.concat([demand, price, baselines], ignore_index=True), truth=truth)
    coverage = verify_coverage(predictions)
    for column in ("task", "model", "strategy"):
        predictions[column] = predictions[column].astype("category")
    del demand, price, baselines, observed
    print("Computing monthly intervals, type/novelty comparisons, calendar checks and alarm windows...", flush=True)
    tables = evaluate_joint(predictions, assignments, signals, sources["events"], args.bootstrap_replicates, args.seed)
    tables["prediction_coverage"] = coverage
    (output / "tables").mkdir()
    for name, table in tables.items():
        table.to_csv(output / "tables" / f"{name}.csv", index=False)
    print("Rendering six joint-analysis figures...", flush=True)
    from .joint_plots import make_joint_figures
    make_joint_figures(tables, assignments, signals, sources["events"], output / "figures")
    for name, digest in hashes.items():
        if file_sha256(reference / name) != digest:
            raise RuntimeError(f"D's fixed reference changed during analysis: {name}")
    source_root = Path(__file__).parent
    summary = {
        "status": "complete_for_frozen_B_C_joint_analysis", "data_sha256": data_hash,
        "reference_output": str(reference), "reference_files_sha256": hashes,
        "fixed_day_types_and_input_detector_refitted": False,
        "input_threshold_unchanged": core["input_threshold"], "input_alarms_unchanged": core["alarms"],
        "price_predictions_source": str(Path(args.price_predictions).resolve()),
        "price_predictions_sha256": file_sha256(args.price_predictions),
        "part_b_training_source_sha256": file_sha256(Path(args.demand_rf).resolve().parents[1] / "train_demand.py"),
        "part_d_source_sha256": {str(p.relative_to(source_root)): file_sha256(p) for p in sorted(source_root.rglob("*.py"))},
        "coverage": _records(coverage), "overall_performance": _records(tables["overall_performance"]),
        "uncertainty_summary": _records(tables["confidence_interval_widths"]),
        "bootstrap_replicates": args.bootstrap_replicates, "seed": args.seed, "environment": env,
        "interval_estimand": "Expected performance of these fixed models under conditions resembling each observed month, assuming within-month stability",
        "alarm_window_definition": "28 days ending on alarm day D versus D+1 through D+28; frozen forecasts in both windows",
        "association_loss_definition": "Demand APE (%) or price misclassification (%); positive association means higher loss",
        "source_report_prose_generated": False,
        "remaining_team_dependencies": ["E error-based drift detector comparison", "E budgeted retraining/adaptation comparisons", "Group-authored final report and submission package"],
        "limitations": [
            "No independent drift ground truth: alarm counts are not detection accuracy, precision or false-positive rates.",
            "Monthly confidence intervals are not predictive intervals for the live week or formal tests of changes between months.",
            "Independent-half-hour normal intervals ignore serial dependence; whole-day resampling preserves within-day dependence but assumes exchangeable independent days.",
            "Normal and Hoeffding bounds are stored without clipping; price accuracy in plots is bounded by the displayed 0--100 axis.",
            "Observed clusters and novelty are retrospective attributes, never inputs used to predict that same day's outcomes.",
            "Pooled type/novelty comparisons are confounded by calendar composition and class balance; calendar checks do not establish causation.",
            "Rank-residual adjustment and first differences are descriptive checks; no iid correlation p-values are reported.",
            "Before/after windows use future outcomes only for retrospective analysis; they never change past alarms or fitted parameters.",
            "A fixed old reference stays shifted after model retraining; repeat alarms inside one exceedance run are not independent change events.",
            "Market-event windows are sourced context, not causal attribution or external model features.",
            "Whether drift-triggered retraining improves performance still requires E's budgeted adaptation experiments.",
        ],
    }
    (output / "run_summary.json").write_text(json.dumps(summary, indent=2, allow_nan=False), encoding="utf-8")
    print(json.dumps({"status": summary["status"], "rows": len(predictions), "series": len(coverage),
                      "tables": len(tables), "output": str(output)}, indent=2), flush=True)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True)
    parser.add_argument("--reference-output", default="outputs/part_d_complete")
    parser.add_argument("--output", help="Default: <reference-output>/joint; must be new or empty")
    parser.add_argument("--price-predictions", default="Part_C_Price_Direction/results/price_predictions_for_part_d.csv")
    parser.add_argument("--demand-rf", default="Part_B_Demand/artifacts/rf_model.joblib")
    parser.add_argument("--demand-handover", help="Optional verified export cache from Part_D_Drift.handover")
    parser.add_argument("--bootstrap-replicates", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=9417)
    parser.add_argument("--strict-versions", action="store_true")
    args = parser.parse_args()
    with threadpool_limits(limits=2):
        run(args)


if __name__ == "__main__":
    main()
